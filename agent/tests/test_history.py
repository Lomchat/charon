"""Tests for agent/charon_agent/history.py (the resume modal's index).

Run: python3 agent/tests/test_history.py
"""
import json
import os
import shutil
import sys
import tempfile
import unittest
from unittest import mock

_AGENT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _AGENT_DIR not in sys.path:
    sys.path.insert(0, _AGENT_DIR)

from charon_agent import history  # noqa: E402

CLAUDE_ID = "11111111-2222-3333-4444-555555555555"
CODEX_ID = "01a00000-0000-7000-8000-000000000001"


def jl(*rows):
    return "".join(json.dumps(r) + "\n" for r in rows)


def claude_user(text, cwd="/srv/app", **extra):
    return {"type": "user", "cwd": cwd, "gitBranch": "main", "timestamp": f"t-{text[:8]}",
            "message": {"role": "user", "content": text}, **extra}


def claude_assistant(*blocks, model="claude-opus-5-5"):
    return {"type": "assistant", "message": {"model": model, "content": list(blocks)}}


class HistoryTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.env = mock.patch.dict(os.environ, {
            "CHARON_AGENT_HOME": os.path.join(self.tmp, "charon"),
            "CLAUDE_CONFIG_DIR": os.path.join(self.tmp, "claude"),
            "CODEX_HOME": os.path.join(self.tmp, "codex"),
        })
        self.env.start()
        history._cache = None
        self.projects = os.path.join(self.tmp, "claude", "projects", "-srv-app")
        os.makedirs(self.projects)
        self.sessions = os.path.join(self.tmp, "codex", "sessions", "2026", "11", "08")
        os.makedirs(self.sessions)

    def tearDown(self):
        history._cache = None
        self.env.stop()
        shutil.rmtree(self.tmp, ignore_errors=True)

    def write(self, path, text, mode="w"):
        with open(path, mode) as fh:
            fh.write(text)

    def claude_file(self):
        return os.path.join(self.projects, f"{CLAUDE_ID}.jsonl")

    def rows(self, **params):
        r = history.index(params)
        self.assertTrue(r["ok"])
        return {row["sessionId"]: row for row in r["sessions"]}

    # ── Claude ──────────────────────────────────────────────────────────────

    def test_claude_row_reads_titles_prompts_and_skips_harness_turns(self):
        self.write(self.claude_file(), jl(
            {"type": "custom-title", "customTitle": "first-name"},
            claude_user("<command-name>/clear</command-name>"),
            claude_user("Caveat: The messages below were generated by the user", isMeta=True),
            claude_user("fix the login page"),
            claude_assistant({"type": "text", "text": "Looking."},
                             {"type": "tool_use", "name": "Edit", "input": {"file_path": "/srv/app/login.ts"}}),
            {"type": "user", "cwd": "/srv/app/sub", "message": {"content": [{"type": "tool_result", "content": "ok"}]}},
            claude_user("now deploy it", cwd="/srv/app/sub"),
            {"type": "custom-title", "customTitle": "Login fix"},
            {"type": "last-prompt", "lastPrompt": "now deploy it please"},
        ))
        row = self.rows()[CLAUDE_ID]
        self.assertEqual(row["kind"], "claude")
        self.assertEqual(row["title"], "Login fix")            # the LATEST title
        self.assertEqual(row["firstPrompt"], "fix the login page")
        self.assertEqual(row["lastPrompt"], "now deploy it please")
        self.assertEqual(row["prompts"], 2)                     # no tool result, meta or tag
        self.assertEqual(row["cwd"], "/srv/app")                # the folder it STARTED in
        self.assertEqual(row["model"], "claude-opus-5-5")
        self.assertFalse(row["approx"])

    def test_claude_growth_reads_only_the_appended_bytes(self):
        self.write(self.claude_file(), jl(claude_user("one"), claude_assistant({"type": "text", "text": "a"})))
        self.assertEqual(self.rows()[CLAUDE_ID]["prompts"], 1)
        off = history._cache["files"][self.claude_file()]["off"]
        # A half-written line is not consumed until it is complete.
        self.write(self.claude_file(), jl(claude_user("two")) + '{"type": "us', "a")
        row = self.rows()[CLAUDE_ID]
        self.assertEqual(row["prompts"], 2)
        self.assertEqual(row["lastPrompt"], "two")
        entry = history._cache["files"][self.claude_file()]
        self.assertGreater(entry["off"], off)
        self.assertLess(entry["off"], os.path.getsize(self.claude_file()))
        self.write(self.claude_file(), 'er", "message": {"content": "three"}}\n', "a")
        self.assertEqual(self.rows()[CLAUDE_ID]["prompts"], 3)

    def test_the_cache_survives_a_restart_and_forgets_deleted_files(self):
        self.write(self.claude_file(), jl(claude_user("hello")))
        self.rows()
        history._cache = None                                    # a daemon restart
        with mock.patch.object(history, "_parse", side_effect=AssertionError("re-read")):
            self.assertIn(CLAUDE_ID, self.rows())
        os.remove(self.claude_file())
        self.assertNotIn(CLAUDE_ID, self.rows())
        self.assertNotIn(self.claude_file(), history._cache["files"])

    def test_big_files_are_sampled_head_and_tail(self):
        filler = claude_assistant({"type": "text", "text": "x" * 2000})
        with mock.patch.multiple(history, FULL_PARSE_MAX=20_000, HEAD_BYTES=4_000, TAIL_BYTES=4_000):
            self.write(self.claude_file(), jl(claude_user("the very first request"), *([filler] * 30),
                                              {"type": "custom-title", "customTitle": "Late title"},
                                              claude_user("the latest request")))
            row = self.rows()[CLAUDE_ID]
        self.assertTrue(row["approx"])
        self.assertEqual(row["firstPrompt"], "the very first request")
        self.assertEqual(row["lastPrompt"], "the latest request")
        self.assertEqual(row["title"], "Late title")

    def test_a_tight_budget_answers_part_and_says_how_much_is_left(self):
        for i in range(3):
            self.write(os.path.join(self.projects, f"{i}0000000-0000-0000-0000-000000000000.jsonl"),
                       jl(claude_user(f"p{i}")))
        clock = iter(range(0, 1000))
        with mock.patch.object(history.time, "monotonic", lambda: next(clock)):
            r = history.index({"budget_ms": 1500})
        self.assertGreater(r["pending"], 0)
        self.assertEqual(len(r["sessions"]) + r["pending"], 3)
        r = history.index({"budget_ms": 5000})
        self.assertEqual((len(r["sessions"]), r["pending"]), (3, 0))

    # ── Codex ───────────────────────────────────────────────────────────────

    def codex_file(self, name=CODEX_ID, folder=None):
        return os.path.join(folder or self.sessions, f"rollout-2026-11-08T10-00-00-{name}.jsonl")

    def test_codex_rows_names_subagents_and_archives(self):
        self.write(self.codex_file(), jl(
            {"type": "session_meta", "payload": {"id": CODEX_ID, "cwd": "/srv/api", "git": {"branch": "dev"}, "source": "cli"}},
            {"type": "turn_context", "payload": {"model": "gpt-6.1-sol", "effort": "high"}},
            {"type": "response_item", "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": "# AGENTS.md instructions for /srv/api"}]}},
            {"type": "event_msg", "payload": {"type": "user_message", "message": "# Context from my IDE setup:\n\n## My request for Codex:\nadd a health route"}},
            {"type": "event_msg", "payload": {"type": "agent_message", "message": "done"}},
            {"type": "event_msg", "payload": {"type": "user_message", "message": "<environment_context>x</environment_context>"}},
            {"type": "event_msg", "payload": {"type": "user_message", "message": "and a test"}},
        ))
        sub = "01a00000-0000-7000-8000-000000000002"
        self.write(self.codex_file(sub), jl(
            {"type": "session_meta", "payload": {"id": sub, "cwd": "/srv/api", "source": {"subagent": {"other": "guardian"}}}},
            {"type": "event_msg", "payload": {"type": "user_message", "message": "review"}},
        ))
        arch = "01a00000-0000-7000-8000-000000000003"
        archived_dir = os.path.join(self.tmp, "codex", "archived_sessions")
        os.makedirs(archived_dir)
        self.write(self.codex_file(arch, archived_dir), jl(
            {"type": "session_meta", "payload": {"id": arch, "cwd": "/srv/old"}},
            {"type": "event_msg", "payload": {"type": "user_message", "message": "old work"}},
        ))
        self.write(os.path.join(self.tmp, "codex", "session_index.jsonl"), jl(
            {"id": CODEX_ID, "thread_name": "Old name"}, {"id": CODEX_ID, "thread_name": "Health route"},
        ))
        rows = self.rows()
        self.assertNotIn(sub, rows)                              # sub-agent rollout
        row = rows[CODEX_ID]
        self.assertEqual((row["title"], row["cwd"], row["branch"]), ("Health route", "/srv/api", "dev"))
        self.assertEqual((row["model"], row["effort"]), ("gpt-6.1-sol", "high"))
        self.assertEqual(row["prompts"], 2)
        self.assertEqual(row["firstPrompt"], "add a health route")
        self.assertEqual(row["lastPrompt"], "and a test")
        self.assertTrue(rows[arch]["archived"])
        self.assertNotIn("archived", row)

    def test_codex_preview_reads_response_items_and_tools(self):
        # Newer rollouts: no user_message events, only response items.
        def msg(role, text):
            kind = "input_text" if role == "user" else "output_text"
            return {"type": "response_item", "timestamp": f"t-{text}", "payload": {"type": "message", "role": role, "content": [{"type": kind, "text": text}]}}
        self.write(self.codex_file(), jl(
            {"type": "session_meta", "payload": {"id": CODEX_ID, "cwd": "/srv/api"}},
            msg("user", "<environment_context>x</environment_context>"),
            msg("user", "first ask"), msg("assistant", "first answer"),
            msg("user", "second ask"),
            {"type": "response_item", "payload": {"type": "custom_tool_call", "name": "apply_patch", "input": "*** Begin Patch\n*** Update File: src/a.ts\n*** Add File: src/b.ts\n*** End Patch"}},
            {"type": "response_item", "payload": {"type": "function_call", "name": "exec_command", "arguments": json.dumps({"cmd": "npm test"})}},
            msg("assistant", "second answer"),
        ))
        self.rows()
        p = history.preview({"kind": "codex", "session_id": CODEX_ID})
        self.assertTrue(p["ok"], p)
        self.assertEqual(p["first"], "first ask")
        self.assertEqual([t["user"] for t in p["turns"]], ["second ask"])   # the first has its own bubble
        turn = p["turns"][0]
        self.assertEqual(turn["answer"], "second answer")
        self.assertEqual([(t["k"], t["t"]) for t in turn["tools"]],
                         [("edit", "src/a.ts"), ("edit", "src/b.ts"), ("cmd", "npm test")])

    # ── Preview ─────────────────────────────────────────────────────────────

    def test_claude_preview_last_exchanges_with_tools(self):
        self.write(self.claude_file(), jl(
            claude_user("start here"), claude_assistant({"type": "text", "text": "ok"}),
            claude_user("then this"),
            claude_assistant({"type": "tool_use", "name": "Bash", "input": {"command": "npm run build"}},
                             {"type": "tool_use", "name": "Bash", "input": {"command": "npm run build"}},
                             {"type": "tool_use", "name": "Grep", "input": {"pattern": "TODO"}}),
            claude_assistant({"type": "text", "text": "Built."}),
            claude_user("last one"), claude_assistant({"type": "text", "text": "Done."}),
        ))
        p = history.preview({"kind": "claude", "session_id": CLAUDE_ID, "turns": 2})
        self.assertTrue(p["ok"], p)
        self.assertEqual(p["first"], "start here")
        self.assertEqual([t["user"] for t in p["turns"]], ["then this", "last one"])
        tools = p["turns"][0]["tools"]
        self.assertEqual([(t["k"], t["t"], t.get("n")) for t in tools],
                         [("cmd", "npm run build", 2), ("search", "TODO", None)])
        self.assertEqual(p["turns"][0]["answer"], "Built.")

    def test_preview_refuses_bad_ids_and_links_out_of_the_history(self):
        for bad in ("../../etc/passwd", "a/b", "", "x" * 200):
            p = history.preview({"kind": "claude", "session_id": bad})
            self.assertFalse(p["ok"])
            self.assertEqual(p["reason"], "invalid")
        secret = os.path.join(self.tmp, "secret.jsonl")
        self.write(secret, jl(claude_user("private")))
        os.symlink(secret, self.claude_file())
        p = history.preview({"kind": "claude", "session_id": CLAUDE_ID})
        self.assertFalse(p["ok"])
        self.assertEqual(p["reason"], "invalid")
        self.assertEqual(history.preview({"kind": "codex", "session_id": "nope"})["reason"], "missing")

    def test_an_account_home_linked_to_the_shared_projects_still_previews(self):
        # §14.115: an account's `projects` is a link to the shared folder.
        shared = os.path.join(self.tmp, "shared-projects", "-srv-app")
        os.makedirs(shared)
        shutil.rmtree(os.path.join(self.tmp, "claude", "projects"))
        os.symlink(os.path.dirname(shared), os.path.join(self.tmp, "claude", "projects"))
        self.write(os.path.join(shared, f"{CLAUDE_ID}.jsonl"), jl(claude_user("linked")))
        self.assertIn(CLAUDE_ID, self.rows())
        self.assertTrue(history.preview({"kind": "claude", "session_id": CLAUDE_ID})["ok"])


