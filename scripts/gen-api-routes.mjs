#!/usr/bin/env node
// Writes server/apiRoutes.generated.ts: one static import per
// server/api/**/route.ts, so the bundler (esbuild) sees every route without
// a filesystem glob. Run by `npm run build`;
// `--check` exits 1 when the committed file is stale (CI).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = path.join(root, 'server', 'api');
const outFile = path.join(root, 'server', 'apiRoutes.generated.ts');

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.name === 'route.ts') out.push(path.relative(apiDir, p).split(path.sep).join('/'));
  }
  return out;
}

export function renderRouteTable(files) {
  const sorted = [...files].sort();
  const lines = [
    '// GENERATED by scripts/gen-api-routes.mjs from server/api/**/route.ts: do not edit.',
    "import type { ApiRouteEntry } from './apiRouter';",
  ];
  sorted.forEach((f, i) => lines.push(`import * as r${i} from './api/${f.replace(/\.ts$/, '')}';`));
  lines.push('', 'export const API_ROUTES: ApiRouteEntry[] = [');
  sorted.forEach((f, i) => lines.push(`  { file: ${JSON.stringify(f)}, mod: r${i} },`));
  lines.push('];', '');
  return lines.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = renderRouteTable(walk(apiDir));
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('server/apiRoutes.generated.ts is stale: run node scripts/gen-api-routes.mjs');
      process.exit(1);
    }
  } else if (current !== text) {
    fs.writeFileSync(outFile, text);
    console.log(`api routes: ${text.match(/^import \* as/gm)?.length ?? 0} written`);
  }
}
